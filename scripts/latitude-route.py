#!/usr/bin/env python3
"""LATITUDE の街のページ「凛の1日の道」の、歩く道の線を作る（2026-11-11）。

地点（時刻の順）を、OpenStreetMap の歩行者ルートで一度だけ計算し、線を数メートル単位で単純化して保存する。
ページを開くたびには計算しない（components/latitude/CityRouteMap.tsx がこの JSON を読む）。

計算の仕組み：FOSSGIS の OSRM（歩行者 routed-foot。https://routing.openstreetmap.de/）。地図データ © OpenStreetMap contributors。
Google の道案内のデータは使わない（Google の地図以外に描くのは規約違反のため）。

使い方（地点は lib/latitude-places.ts の route の coords と同じ順・同じ値。「緯度,経度」）：
  python3 scripts/latitude-route.py kanazawa 36.57778,136.64912 36.57187,136.65578 ...
  → lib/latitude-routes/kanazawa.json
  --response r.json  すでに取ってある OSRM の返事を使う（同じ地点で何度も叩かないため）
  --tol 3            単純化の許容（メートル）
"""
import argparse, datetime, json, math, sys, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OSRM = 'https://routing.openstreetmap.de/routed-foot/route/v1/driving/'
UA = 'LATITUDE-route/1.0 (vual.jp)'


def rdp(pts, tol):
    """Ramer–Douglas–Peucker。pts は [(x, y)]（メートル）。残す番号を返す"""
    if len(pts) < 3:
        return list(range(len(pts)))
    keep = {0, len(pts) - 1}
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (x0, y0), (x1, y1) = pts[a], pts[b]
        dx, dy = x1 - x0, y1 - y0
        L = math.hypot(dx, dy) or 1e-9
        i, dmax = -1, -1.0
        for k in range(a + 1, b):
            d = abs(dy * (pts[k][0] - x0) - dx * (pts[k][1] - y0)) / L
            if d > dmax:
                i, dmax = k, d
        if dmax > tol:
            keep.add(i)
            stack += [(a, i), (i, b)]
    return sorted(keep)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('slug')
    ap.add_argument('stops', nargs='+', help='緯度,経度（時刻の順）')
    ap.add_argument('--response')
    ap.add_argument('--tol', type=float, default=3.0)
    a = ap.parse_args()
    stops = [tuple(float(v) for v in s.split(',')) for s in a.stops]
    if len(stops) < 2:
        sys.exit('地点は2つ以上')

    if a.response:
        d = json.load(open(a.response))
    else:
        url = OSRM + ';'.join(f'{lon},{lat}' for lat, lon in stops) + '?overview=false&geometries=geojson&steps=true'
        req = urllib.request.Request(url, headers={'User-Agent': UA})
        with urllib.request.urlopen(req, timeout=60) as r:
            d = json.load(r)
    if d.get('code') != 'Ok':
        sys.exit(f'OSRM: {d.get("code")} {d.get("message", "")}')
    route = d['routes'][0]

    lat0 = sum(s[0] for s in stops) / len(stops)
    KX, KY = 111320 * math.cos(math.radians(lat0)), 110574
    legs = []
    for k, leg in enumerate(route['legs']):
        line = []
        for st in leg['steps']:
            for lon, lat in st['geometry']['coordinates']:
                if not line or line[-1] != (lat, lon):
                    line.append((lat, lon))
        # 地点の印から道の線へ（道に寄せた位置と印の位置が数十メートル違う所。兼六園の中など）は、まっすぐつなぐ
        (alat, alon), (blat, blon) = stops[k], stops[k + 1]
        line = [(alat, alon)] + line + [(blat, blon)]
        xy = [((lon - stops[0][1]) * KX, (stops[0][0] - lat) * KY) for lat, lon in line]
        keep = rdp(xy, a.tol)
        legs.append({
            'distance': round(leg['distance']),  # メートル
            'duration': round(leg['duration']),  # 秒（OSRM の歩く速さ）
            'line': [[round(line[i][0], 6), round(line[i][1], 6)] for i in keep],
        })

    out = {
        'note': 'Walking route between the day\'s stops, in order. Computed once with the FOSSGIS OSRM foot profile '
                '(routing.openstreetmap.de) on OpenStreetMap data (© OpenStreetMap contributors, ODbL). '
                'Simplified with Ramer–Douglas–Peucker. Coordinates are [lat, lon]. Generated by scripts/latitude-route.py.',
        'source': 'FOSSGIS OSRM routed-foot (OpenStreetMap)',
        'computed': datetime.date.today().isoformat(),
        'tolerance_m': a.tol,
        'stops': [[lat, lon] for lat, lon in stops],
        'distance': round(route['distance']),
        'duration': round(route['duration']),
        'legs': legs,
    }
    dst = ROOT / 'lib' / 'latitude-routes' / f'{a.slug}.json'
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(json.dumps(out, ensure_ascii=False, separators=(',', ':')) + '\n')
    n = sum(len(l['line']) for l in legs)
    print(f'{dst}  {out["distance"]} m  {round(out["duration"] / 60)} min  {len(legs)} legs  {n} points')


if __name__ == '__main__':
    main()
