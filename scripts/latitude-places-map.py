#!/usr/bin/env python3
"""2026-11-11 LATITUDE の「場所から探す」ページ（/latitude/places。components/latitude/PlacesMap.tsx）の地図の形を作る。

世界の地図は一覧ページの「Where they are」と同じ lib/latitude-map.ts の LAND_PATH・同じ図法（project）。
国へ寄った時の細かい形は Natural Earth 50m の国（public domain。vault.vual.jp outputs/latitude-magazine/geo/ne50.geojson）を、
同じ図法で写して public/latitude/placesmap.json に書く（画面が開いてから読む）。外部の地図サービスは使わない。

- countries：街の案内がある国の、寄った時の範囲（view）と輪郭（d）。遠い島は範囲の外なら落とす。
- context：寄った時に周りに見える国（範囲の地域に入る国すべて）。国境はうすい線になる。
- 日本は沖縄（南西諸島）を、太平洋の空いた所に小さな枠で入れる（inset）。

国を足す時は VIEWS に1行足して、もう一度回す：python3 scripts/latitude-places-map.py <ne50.geojson>
"""
import json, math, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LON0, LAT1, K, SC = -28, 73, 0.694658, 8.087396  # lib/latitude-map.ts と同じ
P = lambda lon, lat: ((lon - LON0) * K * SC, (LAT1 - lat) * SC)

# 国コード → 寄った時の範囲（西・南・東・北）
VIEWS = {
    'JP': (128.6, 30.6, 146.2, 45.7),
    'GB': (-8.4, 49.8, 2.0, 59.0),
    'DK': (7.9, 54.5, 15.3, 57.9),
    'IT': (6.5, 36.5, 18.6, 47.2),
    'IS': (-24.6, 63.2, -13.3, 66.6),
    'AT': (9.4, 46.3, 17.3, 49.1),
    'SE': (10.9, 55.2, 24.3, 69.1),
}
# 周りの国を描く地域（西・南・東・北）
REGIONS = [(-30, 33, 35, 72), (115, 20, 152, 50)]
# 沖縄の枠：元の範囲（西・南・東・北）→ 置く範囲（日本の範囲の中の、太平洋の空いた所）
INSET_JP = {'src': (122.8, 24.0, 131.4, 28.8), 'dst': (139.6, 30.9, 145.9, 33.6)}
TOL = 0.02  # 地図の単位（世界の幅 1000）。日本に寄ると1単位が15px ほどなので、0.3px

def rdp(pts, tol):
    if len(pts) < 3: return pts
    (x0, y0), (x1, y1) = pts[0], pts[-1]
    dx, dy = x1 - x0, y1 - y0; L = math.hypot(dx, dy) or 1e-9
    i, dmax = 0, -1.0
    for k in range(1, len(pts) - 1):
        d = abs(dy * (pts[k][0] - x0) - dx * (pts[k][1] - y0)) / L
        if d > dmax: i, dmax = k, d
    if dmax <= tol: return [pts[0], pts[-1]]
    return rdp(pts[: i + 1], tol)[:-1] + rdp(pts[i:], tol)

def simplify_ring(pts, tol):
    far = max(range(len(pts)), key=lambda i: (pts[i][0] - pts[0][0]) ** 2 + (pts[i][1] - pts[0][1]) ** 2)
    if not 0 < far < len(pts) - 1: return pts
    return rdp(pts[: far + 1], tol)[:-1] + rdp(pts[far:], tol)

def area(p):
    return abs(sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(p, p[1:] + p[:1]))) / 2

def path(rings, tol=TOL, min_area=0.002, nd=2):
    d = ''
    for pts in rings:
        if area(pts) < min_area: continue
        q = [(round(x, nd), round(y, nd)) for x, y in simplify_ring(pts, tol)]
        if len(q) < 3: continue
        d += f'M{q[0][0]} {q[0][1]}' + ''.join(f'l{round(b[0]-a[0],nd):g} {round(b[1]-a[1],nd):g}' for a, b in zip(q, q[1:])) + 'z'
    return d

def rings_of(f):
    g = f['geometry']
    polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    return [poly[0] for poly in polys]  # 外側の輪だけ（湖の穴は小さな地図では要らない）

def inside(ring, box):
    w, s, e, n = box
    return any(w <= lon <= e and s <= lat <= n for lon, lat in ring)

def code(f):
    p = f['properties']
    c = p.get('ISO_A2')
    return p.get('ISO_A2_EH') if c in (None, '-99') else c

def main():
    feats = json.load(open(sys.argv[1]))['features']
    by = {code(f): f for f in feats}
    out = {'note': 'Generated by scripts/latitude-places-map.py from Natural Earth 50m (public domain). Same projection as lib/latitude-map.ts.', 'countries': {}}
    for c, box in VIEWS.items():
        f = by[c]
        rings = [[P(lon, lat) for lon, lat in r] for r in rings_of(f) if inside(r, box)]
        x0, y0 = P(box[0], box[3]); x1, y1 = P(box[2], box[1])
        item = {'view': [round(x0, 2), round(y0, 2), round(x1 - x0, 2), round(y1 - y0, 2)], 'd': path(rings)}
        if c == 'JP':
            sw, ss, se, sn = INSET_JP['src']; dw, ds, de, dn = INSET_JP['dst']
            a0, b0 = P(sw, sn); a1, b1 = P(se, ss); c0, d0 = P(dw, dn); c1, d1 = P(de, ds)
            k = min((c1 - c0) / (a1 - a0), (d1 - d0) / (b1 - b0))
            ox, oy = c0 + ((c1 - c0) - (a1 - a0) * k) / 2, d0 + ((d1 - d0) - (b1 - b0) * k) / 2
            T = lambda x, y: (ox + (x - a0) * k, oy + (y - b0) * k)
            irings = [[T(*P(lon, lat)) for lon, lat in r] for r in rings_of(f) if inside(r, INSET_JP['src']) and not inside(r, box)]
            item['inset'] = {'box': [round(c0, 2), round(d0, 2), round(c1 - c0, 2), round(d1 - d0, 2)], 'd': path(irings, TOL / 2, 0.0005)}
        out['countries'][c] = item
    ctx = []
    for f in feats:
        rs = [r for r in rings_of(f) if any(inside(r, R) for R in REGIONS)]
        ctx += [[P(lon, lat) for lon, lat in r] for r in rs]
    out['context'] = path(ctx, 0.08, 0.01, 1)  # 周りの国は背景なので粗くてよい
    dst = ROOT / 'public' / 'latitude' / 'placesmap.json'
    dst.write_text(json.dumps(out, ensure_ascii=False, separators=(',', ':')))
    print(dst, f'{dst.stat().st_size / 1024:.0f} KB', {c: len(v['d']) for c, v in out['countries'].items()}, 'context', len(out['context']))

if __name__ == '__main__':
    main()
