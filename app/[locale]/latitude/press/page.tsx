const latNum = (s: string) => parseFloat(s);

export async function generateMetadata({ params }: { params: Promise<{ locale: string }> }): Promise<Metadata> {
  const { locale } = await params;
  const ja = locale === 'ja';
  const t = ja ? T.ja : T.en;
  const path = '/latitude/press';
  return {
    title: t.title,
    description: t.description,
    alternates: {
      canonical: `/${ja ? 'ja' : 'en'}${path}`,
      languages: { en: `/en${path}`, ja: `/ja${path}`, 'x-default': `/en${path}` },
    },
    openGraph: { type: 'website', siteName: 'VUAL', title: t.title, description: t.description, url: `https://vual.jp/${ja ? 'ja' : 'en'}${path}` },
  };
}

export default async function LatitudePressPage({ params }: { params: Promise<{ locale: string }> }) {
  const { locale } = await params;
  const ja = locale === 'ja';
  const t = ja ? T.ja : T.en;
  const body = ja ? { fontFamily: MINCHO } : { fontFamily: SERIF };
  const para = ja ? 'text-[15px] leading-[2.1]' : 'text-[17px] leading-relaxed';

  // 数字は号と街のデータから数える（号が増えても直さずに済む）
  const issues = liveIssues();
  const cityOf = (slug: string) => CITIES.find((c) => (c.issue ?? c.slug) === slug);
  const countries = new Set(issues.map((i) => cityOf(i.slug)?.countryCode ?? 'JP'));
  const lats = issues.map((i) => ({ i, n: latNum(i.latitude) })).filter((x) => !Number.isNaN(x.n)).sort((a, z) => a.n - z.n);
  const low = lats[0]?.i;
  const high = lats[lats.length - 1]?.i;
  // 号の街の名前。日本語は街の案内の名前を使う（号の題が国の名前の号＝アイスランドは、案内の街＝レイキャビクと違うので別に持つ）
  const JA_ISSUE_CITY: Record<string, string> = { Iceland: 'アイスランド' };
  const cityName = (slug: string, fallback: string) => {
    if (!ja) return fallback;
    const c = cityOf(slug);
    return JA_ISSUE_CITY[fallback] ?? (c && c.name === fallback ? c.nameJa : fallback);
  };
  const paren = (s: string) => (ja ? `（${s}）` : ` (${s})`);
  const notes = issues.filter((i) => getNote(i.slug)).length;
  const places = CITIES.reduce((n, c) => n + c.places.length, 0);
  const first = issues.map((i) => i.published).sort()[0];
  const firstLabel = first
    ? new Date(`${first}-01T00:00:00Z`).toLocaleDateString(ja ? 'ja-JP' : 'en-GB', { year: 'numeric', month: 'long', timeZone: 'UTC' })
    : '';

  const g = t.glance;
  const glance: [string, string][] = [
    [g.issues, String(issues.length)],
    [g.cities, `${new Set(issues.map((i) => i.city)).size}${paren(g.countries(countries.size))}`],
    ...(low && high ? [[g.range, `${low.latitude}${paren(cityName(low.slug, low.city))} – ${high.latitude}${paren(cityName(high.slug, high.city))}`] as [string, string]] : []),
    [g.travellers, String(PEOPLE.length)],
    [g.notes, g.notesVal(notes)],
    [g.guides, g.guidesVal(CITIES.length, places)],
    [g.first, firstLabel],
    [g.languages, g.languagesVal],
  ];

  // 画像：服が全部 VUAL オリジナルの号だけ（公開済みのものに限る）
  const pressIssues = PRESS_IMAGE_ISSUES.map((s) => issues.find((i) => i.slug === s)).filter((i): i is NonNullable<typeof i> => !!i);

  return (
    <div className="min-h-screen" style={{ background: PAPER, color: INK }}>
      <JsonLd data={periodicalJsonLd()} />
      <IssueStrip locale={locale} />
      <header className="mx-auto max-w-3xl px-4 pb-10 pt-16 md:px-8 md:pt-28">
        <p className="text-[11px] uppercase tracking-[0.35em]" style={{ color: MUTE }}>
          <Link href={`/${locale}/latitude`} style={{ color: MUTE }}>Latitude</Link>&nbsp;&nbsp;·&nbsp;&nbsp;{t.label}
        </p>
        <h1 className="mt-5 text-[56px] uppercase leading-none md:text-[96px]" style={{ fontFamily: SERIF, fontWeight: 400, letterSpacing: '0.12em', color: INK }}>
          Latitude
        </h1>
        <p className="mt-6 text-[17px] leading-relaxed md:text-[20px]" style={body}>{t.lead}</p>
      </header>

      <main className="mx-auto max-w-3xl px-4 pb-24 md:px-8">
        <section className="border-t pt-12" style={{ borderColor: RULE }}>
          <SectionLabel>{t.briefTitle}</SectionLabel>
          <p className={para} style={body}>{t.brief}</p>
          <div className="mt-5"><CopyText text={t.brief} label={t.copy} done={t.copied} /></div>
        </section>

        <section className="mt-16">
          <SectionLabel>{t.fullTitle}</SectionLabel>
          <div className="space-y-5">
            {t.full.map((s) => <p key={s} className={para} style={body}>{s}</p>)}
          </div>
          <div className="mt-5"><CopyText text={t.full.join('\n\n')} label={t.copy} done={t.copied} /></div>
        </section>

        <section className="mt-16">
          <SectionLabel>{t.howTitle}</SectionLabel>
          <dl className="border-t" style={{ borderColor: RULE }}>
            {t.how.map(([k, v]) => (
              <div key={k} className="gap-6 border-b py-4 md:flex" style={{ borderColor: RULE }}>
                <dt className="mb-2 w-44 shrink-0 pt-[3px] text-[10px] uppercase tracking-[0.3em] md:mb-0" style={{ color: MUTE }}>{k}</dt>
                <dd className="text-[15px] leading-relaxed" style={body}>
                  {v}
                  {(k === 'Decided by people' || k === '人が決める') && (
                    <>
                      {' '}
                      <Link href={`/${locale}/latitude/editor`} className="underline underline-offset-4" style={{ color: INK, textDecorationColor: 'rgba(30,29,27,0.3)' }}>
                        {ja ? '制作ノートの一覧' : 'The working notes'}
                      </Link>
                    </>
                  )}
                </dd>
              </div>
            ))}
          </dl>
        </section>

        <section className="mt-16">
          <SectionLabel>{t.glanceTitle}</SectionLabel>
          <dl className="border-t" style={{ borderColor: RULE }}>
            {glance.map(([k, v]) => (
              <div key={k} className="flex gap-6 border-b py-4" style={{ borderColor: RULE }}>
                <dt className="w-36 shrink-0 pt-[3px] text-[10px] uppercase tracking-[0.3em] md:w-48" style={{ color: MUTE }}>{k}</dt>
                <dd className="text-[15px]" style={body}>{v}</dd>
              </div>
            ))}
          </dl>
        </section>

        <section className="mt-16">
          <SectionLabel>{t.imagesTitle}</SectionLabel>
          <p className={`${para} mb-10`} style={body}>{t.imagesLead}</p>
          <ul className="grid grid-cols-2 gap-x-5 gap-y-10 md:grid-cols-3">
            {pressIssues.map((i) => {
              const cover = assetUrl(i, `pages/${i.pages[0]?.file ?? '01.jpg'}`);
              const film = assetUrl(i, 'cover.jpg');
              const who = personOf(i)?.name;
              return (
                <li key={i.slug}>
                  <a href={cover} target="_blank" rel="noopener">
                    {/* eslint-disable-next-line @next/next/no-img-element */}
                    <img src={cover} alt={`LATITUDE ${i.latitude} ${i.city}${who ? `, ${who}` : ''}`} loading="lazy" className="w-full object-cover" style={{ aspectRatio: '3 / 4' }} />
                  </a>
                  <p className="mt-3 text-[10px] uppercase tracking-[0.3em]">{i.latitude}&nbsp;&nbsp;{ja ? cityName(i.slug, i.city) : i.city}</p>
                  <p className="mt-2 flex flex-col gap-1 text-[10px] uppercase tracking-[0.2em]" style={{ color: MUTE }}>
                    <a href={cover} target="_blank" rel="noopener" className="underline-offset-4 hover:underline" style={{ color: MUTE }}>{t.carousel}</a>
                    <a href={film} target="_blank" rel="noopener" className="underline-offset-4 hover:underline" style={{ color: MUTE }}>{t.film}</a>
                  </p>
                </li>
              );
            })}
          </ul>
        </section>

        <section className="mt-16">
          <SectionLabel>{t.editorTitle}</SectionLabel>
          <p className={para} style={body}>{t.editor}</p>
          <Link href={`/${locale}/latitude/editor`} rel="author" className="mt-5 inline-block border-b pb-1 text-[10px] uppercase tracking-[0.3em]" style={{ color: INK, borderColor: INK }}>
            {t.editorLink}&nbsp;&nbsp;→
          </Link>
        </section>

        <section className="mt-16">
          <SectionLabel>{t.creditTitle}</SectionLabel>
          <dl className="border-t" style={{ borderColor: RULE }}>
            {t.credit.map(([k, v]) => (
              <div key={k} className="flex gap-6 border-b py-4" style={{ borderColor: RULE }}>
                <dt className="w-36 shrink-0 pt-[3px] text-[10px] uppercase tracking-[0.3em] md:w-48" style={{ color: MUTE }}>{k}</dt>
                <dd className="text-[15px]" style={body}>{v.startsWith('https://') ? <a href={v} style={{ color: INK }}>{v}</a> : v}</dd>
              </div>
            ))}
          </dl>
        </section>

        <section className="mt-16">
          <SectionLabel>{t.contactTitle}</SectionLabel>
          <p className="text-[10px] uppercase tracking-[0.3em]" style={{ color: MUTE }}>{t.contactLabel}</p>
          <p className="mt-2 text-[20px]" style={{ fontFamily: SERIF }}>
            <a href="mailto:editor@vual.jp" style={{ color: INK }}>editor@vual.jp</a>
          </p>
          <p className={`${para} mt-4`} style={body}>{t.contactLine}</p>
          <ul className="mt-8 flex flex-wrap gap-x-7 gap-y-2 text-[10px] uppercase tracking-[0.3em]">
            {t.more.map(([label, path]) => (
              <li key={path}>
                <Link href={`/${locale}/latitude/${path}`} style={{ color: INK }}>{label}&nbsp;&nbsp;→</Link>
              </li>
            ))}
          </ul>
        </section>
      </main>

      <footer className="border-t px-4 py-16 md:px-8" style={{ borderColor: 'rgba(30,29,27,0.12)' }}>
        <div className="mx-auto max-w-6xl">
          <PublishedBy locale={locale} />
        </div>
      </footer>
    </div>
  );
}
